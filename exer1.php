<?php 

    echo "While: ";
    echo "<br>";
    $n1 = 1;
    while($n1 <= 10){
        echo $n1 . "<br>";
        $n1 = $n1 + 1;
    }

    echo "Do-While: ";
    echo "<br>";
    $n1 = 1; 
    do {
        echo $n1. "<br>";
        $n1 = $n1 + 1;
    }while($n1 <= 10);

    echo "For: ";
    echo "<br>";
    $n1 = 1;
    for($n1=1;$n1<=10;$n1++){
        echo $n1. "<br>";
    }
?>
